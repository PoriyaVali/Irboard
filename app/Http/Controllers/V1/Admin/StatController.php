    /**
     * The last 31 days of the daily statistics, five entries per day.
     *
     * Each entry keeps the `type` label and "m-d" `date` the web admin's chart
     * reads, and now also says which column it is (`key`) and which day
     * (`record_at`), so a client can read it without matching labels or
     * guessing the year.
     *
     * Amounts are as stored. They were divided by 100, a v2board habit for
     * prices kept in cents; this panel keeps them in toman (the dashboard
     * shows month_income as is), so the chart's income read a hundredth of
     * what it was.
     */
    public function getOrder(Request $request)
    {
        $statistics = Stat::where('record_type', 'd')
            ->limit(31)
            ->orderBy('record_at', 'DESC')
            ->get()
            ->toArray();
        $columns = [
            'register_count' => 'تعداد ثبت‌نام',
            'paid_total' => 'مبلغ دریافتی',
            'paid_count' => 'تعداد تراکنش دریافتی',
            'commission_total' => 'مبلغ پورسانت (پرداخت‌شده)',
            'commission_count' => 'تعداد پورسانت (پرداخت‌شده)',
        ];
        $result = [];
        foreach ($statistics as $statistic) {
            $date = date('m-d', $statistic['record_at']);
            foreach ($columns as $key => $type) {
                $result[] = [
                    'type' => $type,
                    'key' => $key,
                    'date' => $date,
                    'record_at' => (int)$statistic['record_at'],
                    'value' => (int)$statistic[$key],
                ];
            }
        }
        $result = array_reverse($result);
        return [
            'data' => $result
        ];
    }

    private function withProtocolNodes(array $servers): array
    {
        foreach (\App\Protocols\Mihomo\ProtocolRegistry::all() as $type => $definition) {
            if (\Illuminate\Support\Facades\Schema::hasTable($definition['table'])) {
                $model = $definition['model'];
                $servers[$type] = $model::whereNull('parent_id')->get()->toArray();
            }
        }
        return $servers;
    }

    public function getServerLastRank()
    {
        $servers = [
            'shadowsocks' => ServerShadowsocks::where('parent_id', null)->get()->toArray(),
            'v2ray' => ServerVmess::where('parent_id', null)->get()->toArray(),
            'trojan' => ServerTrojan::where('parent_id', null)->get()->toArray(),
            'vmess' => ServerVmess::where('parent_id', null)->get()->toArray(),
            'vless' => ServerVless::where('parent_id', null)->get()->toArray(),
            'tuic' => ServerTuic::where('parent_id', null)->get()->toArray(),
            'hysteria'=> ServerHysteria::where('parent_id', null)->get()->toArray(),
            'anytls' => ServerAnytls::where('parent_id', null)->get()->toArray(),
            'v2node' => ServerV2node::where('parent_id', null)->get()->toArray(),
            'mdns' => ServerMdns::where('parent_id', null)->get()->toArray(),
            'trusttunnel' => ServerTrusttunnel::where('parent_id', null)->get()->toArray()
        ];
        $servers = $this->withProtocolNodes($servers);
        $startAt = strtotime('-1 day', strtotime(date('Y-m-d')));
        $endAt = strtotime(date('Y-m-d'));
        $statistics = StatServer::select([
            'server_id',
            'server_type',
            'u',
            'd',
            DB::raw('(u+d) as total')
        ])
            ->where('record_at', '>=', $startAt)
            ->where('record_at', '<', $endAt)
            ->where('record_type', 'd')
            ->limit(15)
            ->orderBy('total', 'DESC')
            ->get()
            ->toArray();
        foreach ($statistics as $k => $v) {
            foreach (($servers[$v['server_type']] ?? []) as $server) {
                if ($server['id'] === $v['server_id']) {
                    $statistics[$k]['server_name'] = $server['name'];
                }
            }
            $statistics[$k]['total'] = $statistics[$k]['total'] / 1073741824;
        }
        array_multisort(array_column($statistics, 'total'), SORT_DESC, $statistics);
        return [
            'data' => $statistics
        ];
    }

